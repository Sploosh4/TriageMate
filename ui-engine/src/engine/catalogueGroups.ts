const assignments = new Map<string, CatalogueGroup>();
for (const [group, names] of Object.entries(catalogueAssignments)) {
  for (const name of names) {
    if (assignments.has(name)) throw new Error(`Duplicate catalogue assignment: ${name}`);
    assignments.set(name, group as CatalogueGroup);
  }
}

export function groupForRelation(relation: { schema: string; name: string }): CatalogueGroup {
  return assignments.get(`${relation.schema}.${relation.name}`) ?? 'other';
}
