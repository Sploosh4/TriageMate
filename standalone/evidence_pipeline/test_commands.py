def cleanup(scope):
    # Only UUIDs generated by this test, never accepted fixture or lab records.
    with local_database().connect() as conn, conn.cursor() as cur:
        cur.execute("SELECT pg_advisory_xact_lock(731904217)")
        cur.execute("SELECT to_regclass('evidence_pipeline.enrichment_requests')")
        if cur.fetchone()[0] is not None:
            cur.execute(
                "DELETE FROM evidence_pipeline.enrichment_requests q WHERE cause_receipt_id IN (SELECT r.id FROM evidence.observation_receipts r JOIN evidence.collection_attempts a ON a.id=r.collection_attempt_id WHERE a.connection_id=%s) AND NOT EXISTS(SELECT 1 FROM evidence_pipeline.enrichment_runs run WHERE run.request_id=q.id)",
                (scope.connection_id,),
            )
        cur.execute(
            "DELETE FROM evidence.notification_attempts x USING evidence.notifications n WHERE x.notification_id=n.id AND n.connection_id=%s",
            (scope.connection_id,),
        )
        cur.execute(
            "DELETE FROM evidence.notifications WHERE connection_id=%s",
            (scope.connection_id,),
        )
        cur.execute(
            "DELETE FROM evidence.device_observations WHERE provider_device_id IN (SELECT id FROM evidence.provider_devices WHERE connection_id=%s)",
            (scope.connection_id,),
        )
        cur.execute(
            "DELETE FROM evidence.observation_receipts WHERE collection_attempt_id IN (SELECT id FROM evidence.collection_attempts WHERE connection_id=%s)",
            (scope.connection_id,),
        )
        for table in ("source_revisions", "provider_devices", "collection_attempts"):
            cur.execute(
                sql.SQL("DELETE FROM evidence.{} WHERE connection_id=%s").format(
                    sql.Identifier(table)
                ),
                (scope.connection_id,),
            )
        cur.execute(
            "DELETE FROM evidence_pipeline.authorized_connections WHERE connection_id=%s",
            (scope.connection_id,),
        )
        cur.execute(
            "DELETE FROM evidence.source_connections WHERE id=%s",
            (scope.connection_id,),
        )
        cur.execute(
            "DELETE FROM evidence.microsoft_tenants WHERE id=%s AND NOT EXISTS(SELECT 1 FROM evidence.source_connections WHERE tenant_id=%s)",
            (stable_id("tenant", scope.origin, scope.tenant_id),) * 2,
        )


def test_durable_ingestion_and_replay_visible_to_ui_reader(snapshot):
    from app.services.postgres_query import PostgreSQLQueries

    try:
        assert register(snapshot.scope)
        assert not register(snapshot.scope)
        result = ingest(snapshot)
        assert result["devices"] == 1 and not result["replayed"]
        assert ingest(snapshot)["replayed"]
        with pytest.raises(ReplayConflict):
            ingest(replace(snapshot, payload=snapshot.payload + b" "))
        query = PostgreSQLQueries()
        statement = (
            "SELECT source_name,display_name,managed_flag,source_present,latest_outcome FROM evidence_pipeline.current_device_status WHERE connection_id='"
            + snapshot.scope.connection_id
            + "'::uuid"
        )
        data = json.loads(query.execute({"requestId": str(uuid4()), "sql": statement}))
        assert data["rows"] == [
            ["Entra", "Synthetic workstation", False, True, "success"]
        ]
        failure = replace(
            snapshot,
            execution_id=str(uuid4()),
            finished_at=snapshot.finished_at + timedelta(hours=1),
            outcome="failure",
            complete=False,
            payload=b"[]",
            error_code="unavailable",
        )
        assert ingest(failure)["outcome"] == "failure"
        data = json.loads(query.execute({"requestId": str(uuid4()), "sql": statement}))
        assert data["rows"] == [
            ["Entra", "Synthetic workstation", False, True, "failure"]
        ]
        invalid = replace(
            snapshot,
            execution_id=str(uuid4()),
            finished_at=failure.finished_at + timedelta(hours=1),
            payload=b'[{"id":"invalid-native-id"}]',
        )
        assert ingest(invalid)["outcome"] == "failure"
        assert ingest(invalid)["replayed"]
        with local_database().connect() as conn, conn.cursor() as cur:
            cur.execute(
                "SELECT error_code,input_fingerprint FROM evidence.collection_attempts WHERE id=%s",
                (invalid.execution_id,),
            )
            assert cur.fetchone() == (
                "invalid_source_records",
                invalid.input_fingerprint,
            )
            cur.execute(
                "SELECT count(*) FROM evidence.observation_receipts WHERE collection_attempt_id=%s",
                (invalid.execution_id,),
            )
            assert cur.fetchone() == (0,)
    finally:
        cleanup(snapshot.scope)


