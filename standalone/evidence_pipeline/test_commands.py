@pytest.mark.parametrize("outcome", ["success", "partial", "failure"])
def test_cli_distinguishes_recorded_failure_from_success(
    snapshot, tmp_path, monkeypatch, capsys, outcome
):
    from standalone.evidence_pipeline import commands

    payload = tmp_path / "input.json"
    payload.write_bytes(snapshot.payload)
    monkeypatch.setattr(commands, "load_scope", lambda _: snapshot.scope)
    staged = []

    def fake_ingest(envelope):
        staged.append(envelope)
        return {
            "execution_id": envelope.execution_id,
            "outcome": "success" if envelope.complete else "failure",
            "replayed": False,
        }

    monkeypatch.setattr(commands, "ingest", fake_ingest)
    arguments = [
        "import-devices",
        "--scope",
        "unused",
        "--input",
        str(payload),
        "--execution-id",
        snapshot.execution_id,
        "--started-at",
        snapshot.started_at.isoformat(),
        "--finished-at",
        snapshot.finished_at.isoformat(),
        "--outcome",
        outcome,
    ]
    if outcome == "success":
        commands.main(arguments)
    else:
        with pytest.raises(SystemExit) as raised:
            commands.main(arguments)
        assert raised.value.code == 2
    assert len(staged) == 1
    assert staged[0].outcome == outcome
    receipt = json.loads(capsys.readouterr().out)
    assert receipt["execution_id"] == snapshot.execution_id
    assert receipt["outcome"] == ("success" if outcome == "success" else "failure")


def test_cli_records_malformed_payload_as_failed_attempt(
    snapshot, tmp_path, monkeypatch, capsys
):
    from standalone.evidence_pipeline import commands

    payload = tmp_path / "input.json"
    payload.write_bytes(b"not JSON")
    monkeypatch.setattr(commands, "load_scope", lambda _: snapshot.scope)
    received = []

    def fake_ingest(envelope):
        received.append(envelope)
        return {"execution_id": envelope.execution_id, "outcome": envelope.outcome}

    monkeypatch.setattr(commands, "ingest", fake_ingest)
    with pytest.raises(SystemExit) as raised:
        commands.main(
            [
                "import-devices",
                "--scope",
                "unused",
                "--input",
                str(payload),
                "--execution-id",
                snapshot.execution_id,
                "--started-at",
                snapshot.started_at.isoformat(),
                "--finished-at",
                snapshot.finished_at.isoformat(),
            ]
        )
    assert raised.value.code == 2
    assert received[0].error_code == "invalid_source_payload"
    assert received[0].payload == b"not JSON"
    assert not received[0].complete
    assert json.loads(capsys.readouterr().out)["outcome"] == "failure"


@pytest.mark.parametrize(
    "kind", ["devices", "vulnerability_baseline", "recommendations"]
)
@pytest.mark.parametrize("conflicting", [False, True])
def test_concurrent_registration_preserves_exact_source_identity(
    snapshot, monkeypatch, conflicting, kind
):
    from concurrent.futures import ThreadPoolExecutor
    from threading import Barrier, Event
    from standalone.evidence_pipeline import (
        commands,
        assessment_commands,
        recommendation_commands,
    )
    from standalone.evidence_pipeline.persistence import authority

    parent = None
    target = snapshot.scope
    owner = commands
    if kind != "devices":
        parent = replace(snapshot.scope, source="Defender")
        register(parent)
        target = replace(parent, connection_id=str(uuid4()), input_kind=kind)
        owner = (
            assessment_commands
            if kind == "vulnerability_baseline"
            else recommendation_commands
        )

    verified = Barrier(2)
    entered_twice = Event()
    attempts = []
    original_verify = owner.verify_schema
    original_source = authority.source_connection

    def ready(cursor):
        original_verify(cursor)
        verified.wait(timeout=10)

    def overlapping_insert(cursor, envelope):
        attempts.append(envelope.scope)
        if len(attempts) == 1:
            # Widen the old check-then-insert race. With registration serialized,
            # the second worker cannot enter this insertion branch at all.
            entered_twice.wait(timeout=1)
        else:
            entered_twice.set()
        return original_source(cursor, envelope)

    monkeypatch.setattr(owner, "verify_schema", ready)
    monkeypatch.setattr(authority, "source_connection", overlapping_insert)
    other = (
        replace(target, scope_reference="synthetic-conflicting-source")
        if conflicting
        else target
    )

    def attempt(scope):
        try:
            return register(scope, parent.connection_id if parent else None)
        except ReplayConflict as error:
            return error

    try:
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(attempt, [target, other]))
        assert len(attempts) == 1
        assert sum(result is True for result in results) == 1
        if conflicting:
            assert sum(isinstance(result, ReplayConflict) for result in results) == 1
        else:
            assert sum(result is False for result in results) == 1
        with local_database().connect() as conn, conn.cursor() as cur:
            cur.execute(
                "SELECT c.scope_reference FROM evidence.source_connections c JOIN evidence_pipeline.authorized_connections a ON a.connection_id=c.id WHERE c.id=%s",
                (target.connection_id,),
            )
            assert cur.fetchall() == [(attempts[0].scope_reference,)]
    finally:
        if parent:
            table = (
                "assessment_bindings"
                if kind == "vulnerability_baseline"
                else "recommendation_bindings"
            )
            with local_database().connect() as conn, conn.cursor() as cur:
                cur.execute(
                    sql.SQL(
                        "DELETE FROM evidence_pipeline.{} WHERE connection_id=%s"
                    ).format(sql.Identifier(table)),
                    (target.connection_id,),
                )
        cleanup(target)
        if parent:
            cleanup(parent)
