def clear_public(scope, cve):
    with local_database().connect() as conn, conn.cursor() as cur:
        for table in (
            "epss_observations",
            "kev_observations",
            "cvss_observations",
            "vulnerability_details",
            "vulnerability_references",
        ):
            cur.execute(
                sql.SQL(
                    "DELETE FROM evidence.{} WHERE receipt_id IN (SELECT r.id FROM evidence.observation_receipts r JOIN evidence.source_revisions s ON s.id=r.source_revision_id WHERE s.connection_id=%s)"
                ).format(sql.Identifier(table)),
                (scope.connection_id,),
            )
        cur.execute(
            "DELETE FROM evidence_pipeline.public_claims WHERE source_revision_id IN (SELECT id FROM evidence.source_revisions WHERE connection_id=%s)",
            (scope.connection_id,),
        )
        # This CVE is randomly generated by this test and cannot be a fixture row.
        cur.execute("DELETE FROM evidence.vulnerabilities WHERE cve_id=%s", (cve,))
    cleanup(scope)


def test_committed_public_import_replay_failure_and_reader(tmp_path, capsys):
    value = attempt()
    cve = "CVE-2099-" + str(uuid4().int)
    # Keep the parser's 19-digit source identifier bound.
    cve = cve[:28]
    value = replace(
        value,
        scope=replace(value.scope, connection_id=str(uuid4())),
        payload=value.payload.replace(b"CVE-2026-9999999", cve.encode()),
    )
    from app.services.postgres_query import PostgreSQLQueries

    try:
        assert register(value.scope)
        assert not register(value.scope)
        assert not ingest_public(value)["replayed"]
        assert ingest_public(value)["replayed"]
        query = PostgreSQLQueries()
        statement = (
            "SELECT probability::text,percentile::text FROM evidence_pipeline.current_public_epss_observations WHERE connection_id='"
            + value.scope.connection_id
            + "'::uuid"
        )
        result = json.loads(
            query.execute({"requestId": str(uuid4()), "sql": statement})
        )
        assert result["rows"] == [["0.12345678901234567890123456789", "0"]]
        with local_database().connect() as conn, conn.cursor() as cur:
            verify(cur)
        config = tmp_path / "scope.json"
        config.write_text(json.dumps(asdict(value.scope)))
        data = tmp_path / "invalid.csv"
        data.write_bytes(b"invalid public source data")
        failed_id = str(uuid4())
        with pytest.raises(SystemExit) as exited:
            main(
                [
                    "import-public",
                    "--scope",
                    str(config),
                    "--input",
                    str(data),
                    "--execution-id",
                    failed_id,
                    "--started-at",
                    value.started_at.isoformat(),
                    "--finished-at",
                    (value.finished_at + timedelta(seconds=1)).isoformat(),
                ]
            )
        assert exited.value.code == 2
        assert json.loads(capsys.readouterr().out)["outcome"] == "failure"
        with local_database().connect() as conn, conn.cursor() as cur:
            cur.execute(
                "SELECT outcome,error_code FROM evidence.collection_attempts WHERE id=%s",
                (failed_id,),
            )
            assert cur.fetchone() == ("failure", "invalid_source_payload")
            verify(cur)
    finally:
        clear_public(value.scope, cve)


def test_current_upgrade_accepts_public_registration_and_exact_replay():
    """Exercise actual version guards without repeating the retained-data gate."""
    value = attempt()
    cve = ("CVE-2099-" + str(uuid4().int))[:28]
    value = replace(
        value,
        scope=replace(value.scope, connection_id=str(uuid4())),
        payload=value.payload.replace(b"CVE-2026-9999999", cve.encode()),
    )
    try:
        assert register(value.scope)
        assert not register(value.scope)
        assert not ingest_public(value)["replayed"]
        assert ingest_public(value)["replayed"]
        with local_database().connect() as conn, conn.cursor() as cur:
            cur.execute(
                "SELECT count(*) FROM evidence.collection_attempts WHERE connection_id=%s",
                (value.scope.connection_id,),
            )
            assert cur.fetchone() == (1,)
            cur.execute(
                "SELECT claim FROM evidence_pipeline.public_claims c JOIN evidence.source_revisions r ON r.id=c.source_revision_id WHERE r.connection_id=%s",
                (value.scope.connection_id,),
            )
            assert [row[0] for row in cur.fetchall()] == [
                record.claim for record in normalize_public(value.feed())
            ]
    finally:
        clear_public(value.scope, cve)
