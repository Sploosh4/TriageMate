def _canonical_uuid(name: str, value: str) -> None:
    try:
        parsed = UUID(value)
    except ValueError as exc:
        raise ValueError(f"{name} must be a canonical UUID") from exc
    if value != str(parsed) or parsed.int == 0:
        raise ValueError(f"{name} must be a canonical non-zero UUID")


def _utc_timestamp(name: str, value: str) -> datetime:
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError(f"{name} must be an ISO 8601 timestamp") from exc
    if parsed.utcoffset() is None or parsed.utcoffset().total_seconds() != 0:
        raise ValueError(f"{name} must be UTC")
    return parsed.astimezone(timezone.utc)


def _require_utc(name: str, value: datetime) -> None:
    if value.utcoffset() is None or value.utcoffset().total_seconds() != 0:
        raise ValueError(f"{name} must be UTC")


def _policy_filter(policy_id: str) -> str:
    _canonical_uuid("Intune update policy ID", policy_id)
    return f"(PolicyId eq '{policy_id}')"


def _request_body(policy_id: str) -> dict[str, object]:
    return {
        "reportName": REPORT_NAME,
        "filter": _policy_filter(policy_id),
        "select": list(REPORT_SELECT_FIELDS),
        "format": "csv",
        "localizationType": "LocalizedValuesAsAdditionalColumn",
    }


def _authority_scope_sha256(scope: object) -> str:
    if isinstance(scope, MicrosoftConnectionScope):
        return hashlib.sha256(
            canonical_json(scope.model_dump(mode="json")).encode()
        ).hexdigest()
    values = {
        "agency_id": str(getattr(scope, "agency_id")),
        "tenant_id": str(getattr(scope, "tenant_id")),
        "cloud": str(getattr(scope, "cloud")),
        "data_location": str(getattr(scope, "data_location")),
        "product": str(getattr(scope, "product")),
    }
    return hashlib.sha256(canonical_json(values).encode()).hexdigest()


class IntuneUpdateStatusRecord(StrictModel):
    """One exact downloaded report row with no local risk inference."""

    AADDeviceId: str | None
    AggregateState: str | None
    AggregateState_loc: str | None
    CurrentDeviceUpdateStatus: str | None
    CurrentDeviceUpdateStatus_loc: str | None
    CurrentDeviceUpdateSubstatus: str | None
    CurrentDeviceUpdateSubstatus_loc: str | None
    DeviceId: NonEmptyText
    DeviceName: str | None
    EventDateTimeUTC: NonEmptyText
    LastWUScanTimeUTC: NonEmptyText
    LatestAlertMessage: str | None
    LatestAlertMessage_loc: str | None
    OwnerType: str | None
    PolicyId: NonEmptyText
    UPN: str | None

    @model_validator(mode="after")
    def validate_record(self) -> IntuneUpdateStatusRecord:
        _canonical_uuid("Intune managed device ID", self.DeviceId)
        _canonical_uuid("Intune update policy ID", self.PolicyId)
        if self.AADDeviceId:
            _canonical_uuid("Entra device ID", self.AADDeviceId)
        update_report_timestamp(self.EventDateTimeUTC, "EventDateTimeUTC")
        update_report_timestamp(self.LastWUScanTimeUTC, "LastWUScanTimeUTC")
        return self


class IntuneUpdateReportExport(StrictModel):
    """Sanitized evidence from one complete export job."""

    policy_id: NonEmptyText
    authority_scope_sha256: Sha256
    result: MicrosoftTransportResult
    job_id_sha256: Sha256
    request_sha256: Sha256
    job_response_sha256s: tuple[Sha256, ...]
    download_sha256: Sha256
    request_datetime: datetime
    expiration_datetime: datetime
    observed_at: datetime

    @model_validator(mode="after")
    def validate_export(self) -> IntuneUpdateReportExport:
        _canonical_uuid("Intune update policy ID", self.policy_id)
        for name in ("request_datetime", "expiration_datetime", "observed_at"):
            _require_utc(name, getattr(self, name))
        if self.request_datetime > self.observed_at:
            raise ValueError("report export cannot complete before its request")
        if self.observed_at >= self.expiration_datetime:
            raise ValueError("report export download evidence is expired")
        if not self.job_response_sha256s:
            raise ValueError("report export requires bounded job-response evidence")
        if (
            self.result.input_id != _SOURCE.input_id
            or self.result.source_contract_id != _SOURCE.source_contract_id
        ):
            raise ValueError("report export result does not match row 9")
        return self


class IntuneUpdateReportTransport(Protocol):
    def collect(self, policy_id: str) -> IntuneUpdateReportExport: ...


class InjectedIntuneUpdateReportTransport:
    """Provide a complete synthetic export through the production seam."""

    def __init__(self, export: IntuneUpdateReportExport) -> None:
        self._export = export

    def collect(self, policy_id: str) -> IntuneUpdateReportExport:
        if policy_id != self._export.policy_id:
            raise MicrosoftTransportError(
                "injected report does not match the configured policy"
            )
        return self._export


def _records(
    values: Sequence[Mapping[str, object]],
) -> tuple[IntuneUpdateStatusRecord, ...]:
    expected = set(REPORT_FIELDS)
    parsed = []
    for value in values:
        if set(value) != expected:
            raise ValueError("Intune update report row schema is invalid")
        parsed.append(IntuneUpdateStatusRecord.model_validate(dict(value)))
    return tuple(parsed)


def _transport_result(
    *,
    records: tuple[IntuneUpdateStatusRecord, ...],
    observed_at: datetime,
    request_sha256: str,
    workflow_sha256: str,
) -> MicrosoftTransportResult:
    page = MicrosoftTransportPage(
        page_sequence=0,
        request_url_sha256=request_sha256,
        response_sha256=workflow_sha256,
        observed_at=observed_at,
        records=tuple(item.model_dump(mode="json") for item in records),
        terminal=True,
        continuation_present=False,
    )
    chain = hashlib.sha256(
        json.dumps((workflow_sha256,), separators=(",", ":")).encode()
    ).hexdigest()
    return MicrosoftTransportResult(
        pages=(page,),
        input_id=_SOURCE.input_id,
        source_contract_id=_SOURCE.source_contract_id,
        record_count=len(records),
        page_chain_sha256=chain,
    )


def build_injected_update_report_export(
    *,
    scope: object,
    policy_id: str,
    records: Sequence[Mapping[str, object]],
    observed_at: datetime,
    job_id: str,
) -> IntuneUpdateReportExport:
    """Build exact, sanitized workflow evidence for an injected export."""

    _require_utc("observed_at", observed_at)
    if not job_id or len(job_id) > 256:
        raise ValueError("Intune report job ID is invalid")
    parsed = _records(records)
    body = _request_body(policy_id)
    request_sha256 = hashlib.sha256(canonical_json(body).encode()).hexdigest()
    download_sha256 = hashlib.sha256(
        canonical_json(tuple(item.model_dump(mode="json") for item in parsed)).encode()
    ).hexdigest()
    poll_sha256 = hashlib.sha256(f"synthetic-completed:{job_id}".encode()).hexdigest()
    workflow_sha256 = hashlib.sha256(
        canonical_json(
            {
                "request_sha256": request_sha256,
                "job_response_sha256s": (poll_sha256,),
                "download_sha256": download_sha256,
            }
        ).encode()
    ).hexdigest()
    return IntuneUpdateReportExport(
        policy_id=policy_id,
        authority_scope_sha256=_authority_scope_sha256(scope),
        result=_transport_result(
            records=parsed,
            observed_at=observed_at,
            request_sha256=request_sha256,
            workflow_sha256=workflow_sha256,
        ),
        job_id_sha256=hashlib.sha256(job_id.encode()).hexdigest(),
        request_sha256=request_sha256,
        job_response_sha256s=(poll_sha256,),
        download_sha256=download_sha256,
        request_datetime=observed_at - timedelta(seconds=1),
        expiration_datetime=observed_at + timedelta(hours=1),
        observed_at=observed_at,
    )


