class HttpIntuneUpdateReportTransport:
    """Create, poll, download, and validate one Intune report export."""

    def __init__(
        self,
        *,
        client: httpx.Client,
        prepared: PreparedCollectionContext,
        token: MicrosoftAccessTokenLease,
        timeout_seconds: float = 30.0,
        max_retries: int = 3,
        max_polls: int = 60,
        poll_interval_seconds: float = 5.0,
        max_elapsed_seconds: float = 15 * 60,
        max_rows: int = 1_000_000,
        sleep: Callable[[float], None] = time.sleep,
        now: Callable[[], datetime] = lambda: datetime.now(timezone.utc),
        cancelled: Callable[[], bool] = lambda: False,
    ) -> None:
        if (
            timeout_seconds <= 0
            or max_retries < 0
            or max_polls <= 0
            or max_elapsed_seconds <= 0
        ):
            raise ValueError("Intune report timeout or request limits are invalid")
        if poll_interval_seconds < 0:
            raise ValueError("Intune report polling interval is invalid")
        if max_rows <= 0:
            raise ValueError("Intune report size limits must be positive")
        if prepared.scope.product != "intune":
            raise ValueError("Intune report authority must use an Intune scope")
        if (
            prepared.endpoint.host != "graph.microsoft.com"
            or prepared.endpoint.path_template
            != "/beta/deviceManagement/reports/exportJobs"
        ):
            raise ValueError("Intune report endpoint policy is not exact")
        report_permissions = tuple(_SOURCE.application_permissions)
        isolated_permissions = tuple(
            sorted({*report_permissions, "Device.Read.All", "GroupMember.Read.All"})
        )
        if tuple(prepared.expected_roles) not in (
            report_permissions,
            isolated_permissions,
        ):
            raise ValueError("Intune report permission does not match row 9")
        if (
            prepared.elevated_permission_approval_id is None
            or prepared.elevated_permission_approval_sha256 is None
        ):
            raise ValueError("Intune report write-class permission is not approved")
        self._client = client
        self._prepared = prepared
        self._token = token
        self._timeout = timeout_seconds
        self._max_retries = max_retries
        self._max_polls = max_polls
        self._poll_interval = poll_interval_seconds
        self._max_elapsed = max_elapsed_seconds
        self._max_rows = max_rows
        self._sleep = sleep
        self._now = now
        self._cancelled = cancelled

    def collect(self, policy_id: str) -> IntuneUpdateReportExport:
        workflow_started_at = self._now()
        verify_microsoft_transport_authority(
            prepared=self._prepared,
            token=self._token,
            now=workflow_started_at,
        )
        body = _request_body(policy_id)
        request_bytes = canonical_json(body).encode()
        request_sha256 = hashlib.sha256(request_bytes).hexdigest()
        base_url = urlunsplit(
            (
                self._prepared.endpoint.scheme,
                self._prepared.endpoint.host,
                self._prepared.endpoint.path_template,
                "",
                "",
            )
        )
        created = self._request(
            method="POST",
            url=base_url,
            authorization=self._token.authorization_header(),
            json_body=body,
            expected_status=201,
            accept="application/json",
        )
        created_payload = self._json(created)
        job = self._job(created_payload, policy_id=policy_id)
        job_id_sha256 = hashlib.sha256(job.id.encode()).hexdigest()
        response_hashes = [hashlib.sha256(created.content).hexdigest()]
        if job.status in ("failed", "unknown"):
            raise MicrosoftTransportError("Intune report export creation failed")

        for poll in range(self._max_polls):
            if job.status == "completed":
                break
            if (self._now() - workflow_started_at).total_seconds() >= self._max_elapsed:
                raise MicrosoftTransportError("Intune report deadline was exceeded")
            self._wait(min(self._poll_interval * (2**poll), 60.0))
            poll_url = f"{base_url}/{quote(job.id, safe='')}"
            response = self._request(
                method="GET",
                url=poll_url,
                authorization=self._token.authorization_header(),
                expected_status=200,
                accept="application/json",
            )
            response_hashes.append(hashlib.sha256(response.content).hexdigest())
            next_job = self._job(self._json(response), policy_id=policy_id)
            if next_job.id != job.id:
                raise MicrosoftTransportError(
                    "Intune report polling changed the job identity"
                )
            job = next_job
            if job.status in ("failed", "unknown"):
                raise MicrosoftTransportError("Intune report export failed")
        else:
            raise MicrosoftTransportError("Intune report polling limit was exceeded")

        if job.status != "completed" or not job.url:
            raise MicrosoftTransportError(
                "completed Intune report does not have a download URL"
            )
        request_datetime = _utc_timestamp("requestDateTime", job.requestDateTime)
        expiration_datetime = _utc_timestamp(
            "expirationDateTime", job.expirationDateTime
        )
        download_started_at = self._now()
        _require_utc("report download start", download_started_at)
        if download_started_at >= expiration_datetime:
            raise MicrosoftTransportError("Intune report download URL is expired")
        self._validate_download_url(job.url)
        download = self._request(
            method="GET",
            url=job.url,
            authorization=None,
            expected_status=200,
            accept="application/zip",
        )
        observed_at = self._now()
        _require_utc("report observed_at", observed_at)
        if observed_at >= expiration_datetime:
            raise MicrosoftTransportError("Intune report download expired in transit")
        records = self._download_records(download)
        download_sha256 = hashlib.sha256(download.content).hexdigest()
        workflow_sha256 = hashlib.sha256(
            canonical_json(
                {
                    "request_sha256": request_sha256,
                    "job_response_sha256s": tuple(response_hashes),
                    "download_sha256": download_sha256,
                }
            ).encode()
        ).hexdigest()
        return IntuneUpdateReportExport(
            policy_id=policy_id,
            authority_scope_sha256=_authority_scope_sha256(self._prepared.scope),
            result=_transport_result(
                records=records,
                observed_at=observed_at,
                request_sha256=request_sha256,
                workflow_sha256=workflow_sha256,
            ),
            job_id_sha256=job_id_sha256,
            request_sha256=request_sha256,
            job_response_sha256s=tuple(response_hashes),
            download_sha256=download_sha256,
            request_datetime=request_datetime,
            expiration_datetime=expiration_datetime,
            observed_at=observed_at,
        )

    def _job(self, payload: object, *, policy_id: str) -> _ExportJob:
        if (
            isinstance(payload, dict)
            and set(payload) == {"value"}
            and isinstance(payload["value"], dict)
        ):
            payload = payload["value"]
        if not isinstance(payload, dict) or not set(payload) <= _JOB_FIELDS:
            raise MicrosoftTransportError("Intune report job schema is invalid")
        values = {
            key: value for key, value in payload.items() if key != "@odata.context"
        }
        try:
            job = _ExportJob.model_validate(values)
        except ValueError as exc:
            raise MicrosoftTransportError(
                "Intune report job schema is invalid"
            ) from exc
        if (
            job.filter != _policy_filter(policy_id)
            or job.select != REPORT_SELECT_FIELDS
            or job.snapshotId is not None
            or job.search is not None
            or len(job.id) > 256
            or any(
                character
                not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-"
                for character in job.id
            )
        ):
            raise MicrosoftTransportError("Intune report job changed its request scope")
        return job

    def _request(
        self,
        *,
        method: Literal["GET", "POST"],
        url: str,
        authorization: str | None,
        expected_status: int,
        accept: str,
        json_body: Mapping[str, object] | None = None,
    ) -> httpx.Response:
        retries = 0
        while True:
            if self._cancelled():
                raise MicrosoftTransportCancelled(
                    "Intune report collection was cancelled"
                )
            headers = {"Accept": accept}
            if authorization is not None:
                verify_microsoft_transport_authority(
                    prepared=self._prepared,
                    token=self._token,
                    now=self._now(),
                )
                headers["Authorization"] = authorization
            try:
                deadline = time.monotonic() + self._timeout
                with self._client.stream(
                    method,
                    url,
                    headers=headers,
                    json=json_body,
                    timeout=self._timeout,
                    follow_redirects=False,
                ) as streamed:
                    response_headers = httpx.Headers(streamed.headers)
                    status_code = streamed.status_code
                    if status_code not in (429, 503, expected_status):
                        raise MicrosoftHTTPError(status_code)
                    content = b""
                    if status_code == expected_status:
                        declared_length = streamed.headers.get("Content-Length")
                        if declared_length is not None:
                            try:
                                declared_bytes = int(declared_length)
                            except ValueError as exc:
                                raise MicrosoftTransportError(
                                    "Intune report response length is invalid"
                                ) from exc
                            if declared_bytes < 0:
                                raise MicrosoftTransportError(
                                    "Intune report response length is invalid"
                                )
                        content = read_response_content(
                            streamed, deadline=deadline, cancelled=self._cancelled
                        )
            except httpx.DecodingError:
                raise MicrosoftTransportError(
                    "Intune report response encoding is invalid"
                ) from None
            except httpx.TransportError:
                if retries >= self._max_retries:
                    raise MicrosoftTransportError(
                        "Intune report request failed after retry limit"
                    ) from None
                retries += 1
                self._wait(1.0)
                continue
            if status_code in (429, 503):
                if retries >= self._max_retries:
                    raise MicrosoftTransportError(
                        "Intune report request exhausted the retry limit"
                    )
                retries += 1
                try:
                    delay = float(response_headers.get("Retry-After", "1"))
                except ValueError:
                    delay = 1.0
                self._wait(min(max(delay, 0.0), 60.0))
                continue
            # iter_bytes has already decoded the wire representation.
            response_headers.pop("Content-Encoding", None)
            response_headers.pop("Content-Length", None)
            return httpx.Response(
                status_code,
                headers=response_headers,
                content=content,
            )

    def _wait(self, seconds: float) -> None:
        remaining = seconds
        while remaining > 0:
            if self._cancelled():
                raise MicrosoftTransportCancelled(
                    "Intune report collection was cancelled"
                )
            interval = min(remaining, 0.5)
            self._sleep(interval)
            remaining -= interval
        if self._cancelled():
            raise MicrosoftTransportCancelled("Intune report collection was cancelled")

    def _json(self, response: httpx.Response) -> object:
        content_type = response.headers.get("Content-Type", "").split(";", 1)[0]
        if content_type.casefold() != "application/json":
            raise MicrosoftTransportError("Intune report job content type is invalid")
        try:
            return response.json()
        except ValueError as exc:
            raise MicrosoftTransportError("Intune report job JSON is invalid") from exc

    @staticmethod
    def _validate_download_url(value: str) -> None:
        parsed = urlsplit(value)
        if (
            parsed.scheme != "https"
            or parsed.hostname is None
            or not parsed.hostname.endswith(".blob.core.windows.net")
            or parsed.port not in (None, 443)
            or parsed.username is not None
            or parsed.password is not None
            or parsed.fragment
            or not parsed.path.endswith(".zip")
        ):
            raise MicrosoftTransportError(
                "Intune report download endpoint is not allowed"
            )

    def _download_records(
        self, response: httpx.Response
    ) -> tuple[IntuneUpdateStatusRecord, ...]:
        content_type = response.headers.get("Content-Type", "").split(";", 1)[0]
        if content_type.casefold() not in {
            "application/zip",
            "application/octet-stream",
        }:
            raise MicrosoftTransportError(
                "Intune report download content type is invalid"
            )
        try:
            with ZipFile(BytesIO(response.content)) as archive:
                members = archive.infolist()
                if len(members) != 1:
                    raise MicrosoftTransportError(
                        "Intune report archive must contain one CSV file"
                    )
                member = members[0]
                if (
                    member.is_dir()
                    or member.compress_type not in (ZIP_STORED, ZIP_DEFLATED)
                    or member.flag_bits & 0x1
                    or "/" in member.filename
                    or "\\" in member.filename
                    or not member.filename.casefold().endswith(".csv")
                    or (member.file_size > 0 and member.compress_size == 0)
                ):
                    raise MicrosoftTransportError(
                        "Intune report archive member is unsafe"
                    )
                deadline = time.monotonic() + self._timeout

                def checked_lines(stream):
                    for line in stream:
                        if self._cancelled():
                            raise MicrosoftTransportCancelled(
                                "Intune report collection was cancelled"
                            )
                        if time.monotonic() >= deadline:
                            raise MicrosoftTransportError(
                                "Intune report CSV deadline was exceeded"
                            )
                        yield line
                    if self._cancelled():
                        raise MicrosoftTransportCancelled(
                            "Intune report collection was cancelled"
                        )
                    if time.monotonic() >= deadline:
                        raise MicrosoftTransportError(
                            "Intune report CSV deadline was exceeded"
                        )

                # Decode and validate rows as they arrive from the archive. Do
                # not materialize uncompressed bytes, text and raw row copies.
                with (
                    archive.open(member) as source,
                    TextIOWrapper(source, encoding="utf-8-sig", newline="") as text,
                ):
                    reader = csv.DictReader(checked_lines(text))
                    header = tuple(reader.fieldnames or ())
                    if len(header) != len(set(header)) or set(header) != set(
                        REPORT_FIELDS
                    ):
                        raise MicrosoftTransportError(
                            "Intune report CSV schema is invalid"
                        )
                    rows = []
                    for row in reader:
                        if len(rows) >= self._max_rows or None in row:
                            raise MicrosoftTransportError(
                                "Intune report CSV rows are invalid"
                            )
                        try:
                            rows.append(
                                IntuneUpdateStatusRecord.model_validate(dict(row))
                            )
                        except ValueError as exc:
                            raise MicrosoftTransportError(
                                "Intune report row schema is invalid"
                            ) from exc
                    return tuple(rows)
        except MicrosoftTransportError:
            raise
        except UnicodeDecodeError as exc:
            raise MicrosoftTransportError("Intune report CSV is not UTF-8") from exc
        except csv.Error as exc:
            raise MicrosoftTransportError("Intune report CSV is invalid") from exc
        except (BadZipFile, zlib.error, NotImplementedError, RuntimeError) as exc:
            raise MicrosoftTransportError("Intune report archive is invalid") from exc
